#!/usr/bin/env bash
# PreToolUse (Edit|Write): refuse edits on develop/main and to generated or secret files,
# and say what to do instead.
set -uo pipefail

root="${CLAUDE_PROJECT_DIR:-$(pwd)}"
file=$(jq -r '.tool_input.file_path // empty')
[ -n "$file" ] || exit 0
case "$file" in
  "$root"/*) rel="${file#"$root"/}" ;;
  *) exit 0 ;; # outside the repo
esac

deny() {
  jq -n --arg reason "$1" '{
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      permissionDecision: "deny",
      permissionDecisionReason: $reason
    }
  }'
  exit 0
}

case "$rel" in
  .env.example) ;;
  .env* | */.env*)
    deny "$rel may hold secrets and is off limits. Change .env.example and ask the user to update their own env file." ;;
  pnpm-lock.yaml)
    deny "pnpm-lock.yaml is generated. Change package.json, then run pnpm install." ;;
  next-env.d.ts | .next/*)
    deny "$rel is generated by Next.js. Change the source instead (pnpm build regenerates it)." ;;
  docs/plans/*) exit 0 ;; # gitignored local plans may be written before branching
esac

branch=$(git -C "$root" branch --show-current 2>/dev/null)
case "$branch" in
  develop | main)
    deny "You are on $branch. Work happens on a branch: run \`git switch -c <type>/<slug> develop\` (see CLAUDE.md → Workflow), then edit." ;;
esac

exit 0
